/**
 * Codes that mean the ORGANIZATION's gateway setup is wrong, not the donor's card.
 * A donor retrying a different card will never fix these, so they are worth
 * distinguishing: the giving page can tell the donor it isn't their fault and the
 * charity can be alerted.
 */
const MERCHANT_CONFIG_CODES = new Set(["109", "130", "150", "133", "135"]);

export function isMerchantConfigCode(code: unknown): boolean {
  return MERCHANT_CONFIG_CODES.has(String(code ?? "").trim());
}

export function donorMessage(code: unknown): string {
  const key = String(code ?? "").trim();
  if (MERCHANT_CONFIG_CODES.has(key)) {
    return "This organization can't accept card payments right now. Please let them know.";
  }
  return DONOR_SAFE[key] ?? GENERIC;
}
