/** Codes that mean the transaction was approved. */
export const APPROVED_RESPONSE_CODES = new Set(["000", "002", "003", "200"]);

export function isApprovedCode(code: unknown): boolean {
  return APPROVED_RESPONSE_CODES.has(String(code ?? "").trim());
}

/** The raw Fiserv meaning — for logs and support, never shown to a donor. */
export function describeResponseCode(code: unknown): string | undefined {
  return RESPONSE_CODES[String(code ?? "").trim()];
}

